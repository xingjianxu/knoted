#[tokio::test]
async fn t07_5_cancel_requested_keeps_the_lease() {
    let db = test_db().await;
    let job = enqueue(&db.pool, parse_spec("object-11")).await;
    let lease = jobs::claim(&db.pool, "worker-a")
        .await
        .expect("the claim must not fail")
        .expect("a queued job must be claimable");

    // A cancellation request does not free the resources: the worker still owns
    // the lease until it confirms the cancellation.
    sqlx::query("UPDATE jobs SET state = 'cancel_requested' WHERE id = $1")
        .bind(job.id)
        .execute(&db.pool)
        .await
        .expect("running -> cancel_requested must keep the lease");

    let (state, _, token, locked_by) = load_job(&db.pool, job.id).await;
    assert_eq!(state, "cancel_requested");
    assert_eq!(token, Some(lease.token));
    assert_eq!(locked_by.as_deref(), Some("worker-a"));

    assert!(
        jobs::heartbeat(&db.pool, &lease)
            .await
            .expect("heartbeat must not fail"),
        "a cancel_requested job must still accept heartbeats"
    );
    assert!(
        jobs::finish_with_token(&db.pool, &lease, JobOutcome::Cancelled)
            .await
            .expect("finish must not fail"),
        "a cancel_requested job must still accept the owning token"
    );

    let (state, _, token, locked_by) = load_job(&db.pool, job.id).await;
    assert_eq!(state, "cancelled");
    assert_eq!(
        token, None,
        "confirming the cancellation releases the lease"
    );
    assert_eq!(locked_by, None);

    db.drop().await;
}

#[tokio::test]
async fn t07_5_expired_cancel_requested_lease_is_taken_over() {
    let db = test_db().await;
    let job = enqueue(&db.pool, parse_spec("object-13")).await;
    let stale = jobs::claim(&db.pool, "worker-a")
        .await
        .expect("the claim must not fail")
        .expect("a queued job must be claimable");

    // The worker that was asked to cancel died before confirming. The request
    // must not be lost, and the job must not stay locked forever.
    sqlx::query(
        "UPDATE jobs SET state = 'cancel_requested', lease_expires_at = now() - interval '1 second' \
         WHERE id = $1",
    )
    .bind(job.id)
    .execute(&db.pool)
    .await
    .expect("the lease must be expirable while cancelling");

    let takeover = jobs::claim(&db.pool, "worker-b")
        .await
        .expect("the takeover claim must not fail")
        .expect("an expired cancel_requested lease must be reclaimable");
    assert_eq!(takeover.attempt, 2);
    assert_ne!(takeover.token, stale.token);

    let (state, _, token, locked_by) = load_job(&db.pool, job.id).await;
    assert_eq!(
        state, "cancel_requested",
        "a takeover must not turn a cancellation back into a normal run"
    );
    assert_eq!(token, Some(takeover.token));
    assert_eq!(locked_by.as_deref(), Some("worker-b"));

    assert!(
        !jobs::heartbeat(&db.pool, &stale)
            .await
            .expect("heartbeat must not fail"),
        "the dead worker's token must stay invalid"
    );
    assert!(
        jobs::finish_with_token(&db.pool, &takeover, JobOutcome::Cancelled)
            .await
            .expect("finish must not fail"),
        "the new holder must be able to confirm the cancellation"
    );
    let (state, _, token, _) = load_job(&db.pool, job.id).await;
    assert_eq!(state, "cancelled");
    assert_eq!(token, None);

    db.drop().await;
}

